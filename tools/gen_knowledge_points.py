def build_tree(grades: List[int], subjects: List[str]) -> Dict:
    """按范围生成 {subjects: [...], counts: {...}}（JSON 契约与 import 工具对齐）。

    内容 = 教材主线单元（上方 CURRICULUM 手工教研）+ 每个单元的 4 个课程化
    小节考点（按学科模板、以单元名实例化）+ 每个「年级×学科」的综合复习单元。
    模板化部分用于把知识点密度提升到可用的教学粒度（原 749 → 约 2200），
    后续可按单元逐步替换为更细的人工教研内容。
    """
    blocks = []
    n_units = 0
    n_kps = 0
    skipped = []
    for gnum in grades:
        per_grade = CURRICULUM.get(gnum, {})
        for subj in subjects:
            units = per_grade.get(subj)
            if not units:
                skipped.append({"grade": GRADE_NAMES[gnum], "subject": subj,
                                "reason": "该年级无此学科或暂无课程数据"})
                continue
            abbr = SUBJECT_ABBR[subj]
            nodes = []
            extra = EXTRA_BY_SUBJECT.get(subj, DEFAULT_EXTRA)

            def _kp(code, name, desc, diff, kw, sort):
                return {
                    "name": name, "level": 2, "term": 1,
                    "difficulty": diff, "keywords": kw,
                    "description": desc, "source": "seed",
                    "code": code, "sort": sort, "children": [],
                }

            for ui, (unit_name, kp_list) in enumerate(units, start=1):
                unit_code = f"G{gnum:02d}-{abbr}-U{ui:02d}"
                children = []
                for ki, (kp_name, desc, diff, kw) in enumerate(kp_list, start=1):
                    children.append(_kp(f"{unit_code}-K{ki:02d}", kp_name,
                                        desc, diff, kw, ki))
                # 模板化小节考点：基础→应用→辨析→提升，覆盖四个教学环节
                base = len(children)
                for ti, (label, desc_t, diff, kw) in enumerate(extra, start=1):
                    children.append(_kp(
                        f"{unit_code}-K{base + ti:02d}", label,
                        desc_t.format(u=unit_name), diff, kw, base + ti))
                nodes.append({
                    "name": unit_name, "level": 1, "term": 1,
                    "difficulty": "medium", "keywords": "",
                    "description": f"{GRADE_NAMES[gnum]}{subj}单元：{unit_name}",
                    "source": "seed", "code": unit_code,
                    "sort": ui * 10, "children": children,
                })
                n_units += 1
                n_kps += len(children)

            # 每学科的综合复习单元（知识网络→综合应用→易错规范）
            ui = len(units) + 1
            unit_code = f"G{gnum:02d}-{abbr}-U{ui:02d}"
            comp_children = [
                _kp(f"{unit_code}-K{ci:02d}", name,
                    desc.format(s=subj), diff, kw, ci)
                for ci, (name, desc, diff, kw) in enumerate(COMPREHENSIVE_KPS, start=1)
            ]
            nodes.append({
                "name": COMPREHENSIVE_NAME.format(s=subj), "level": 1, "term": 1,
                "difficulty": "medium", "keywords": "",
                "description": f"{GRADE_NAMES[gnum]}{subj}全册综合复习",
                "source": "seed", "code": unit_code,
                "sort": ui * 10, "children": comp_children,
            })
            n_units += 1
            n_kps += len(comp_children)
            blocks.append({
                "grade_num": gnum, "grade_name": GRADE_NAMES[gnum],
                "subject_name": subj, "nodes": nodes,
            })
    return {
        "meta": {
            "schema_version": SCHEMA_VERSION,
            "basis": "人教版教材（义务教育课程方案与课程标准 2022 年版对齐）",
            "generated_by": "tools/gen_knowledge_points.py",
            "levels": "level1=单元, level2=知识点（含说明/难度/关键词）",
            "scope": {
                "grades": [{"grade_num": g, "grade_name": GRADE_NAMES[g]} for g in grades],
                "subjects": subjects,
            },
            "counts": {
                "grades": len(grades), "subjects": len(subjects),
                "subject_blocks": len(blocks), "units": n_units,
                "knowledge_points": n_kps,
            },
            "skipped": skipped,
            "note": "level3 考点层由 knowledge_level3_seed 单独维护，本文件不包含",
        },
        "subjects": blocks,
    }


def flatten(data: Dict) -> List[List[str]]:
    rows = []
    for block in data["subjects"]:
        for unit in block["nodes"]:
            for kp in unit["children"]:
                rows.append([
                    block["grade_num"], block["grade_name"], block["subject_name"],
                    unit["code"], unit["name"],
                    kp["code"], kp["name"], kp["difficulty"],
                    kp["keywords"], kp["description"],
                ])
    return rows


def print_matrix(data: Dict) -> None:
    print("\n===== 覆盖矩阵（年级 × 学科 → 单元数/知识点数）=====")
    cur = None
    for block in data["subjects"]:
        if block["grade_num"] != cur:
            cur = block["grade_num"]
            print(f"  {GRADE_NAMES[cur]:>2}：", end="")
        u = len(block["nodes"])
        k = sum(len(x["children"]) for x in block["nodes"])
        print(f"{block['subject_name']}({u}单元/{k}点) ", end="")
        nxt = data["subjects"].index(block) + 1
        if nxt >= len(data["subjects"]) or data["subjects"][nxt]["grade_num"] != cur:
            print()
    c = data["meta"]["counts"]
    print(f"\n  合计：{c['grades']} 个年级 / {c['subject_blocks']} 个年级-学科组合 / "
          f"{c['units']} 个单元 / {c['knowledge_points']} 个知识点")
    if data["meta"]["skipped"]:
        print(f"  跳过（该年级无此学科）: "
              f"{', '.join(x['grade'] + x['subject'] for x in data['meta']['skipped'][:8])}"
              f"{' …' if len(data['meta']['skipped']) > 8 else ''}")


def write_outputs(data: Dict, out_dir: str, fmt: str) -> None:
    os.makedirs(out_dir, exist_ok=True)
    if fmt in ("json", "both"):
        path = os.path.join(out_dir, "knowledge_points_pep.json")
        with open(path, "w", encoding="utf-8", newline="\n") as fh:
            json.dump(data, fh, ensure_ascii=False, indent=2)
        print(f"  ✔ JSON: {path}")
    if fmt in ("csv", "both"):
        path = os.path.join(out_dir, "knowledge_points_pep.csv")
        with open(path, "w", encoding="utf-8-sig", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["grade_num", "grade_name", "subject_name", "unit_code",
                        "unit_name", "knowledge_code", "knowledge_name",
                        "difficulty", "keywords", "description"])
            w.writerows(flatten(data))
        print(f"  ✔ CSV : {path}")
        cov = os.path.join(out_dir, "coverage.csv")
        with open(cov, "w", encoding="utf-8-sig", newline="") as fh:
            w = csv.writer(fh)
            w.writerow(["grade_num", "grade_name", "subject_name", "units", "knowledge_points"])
            for block in data["subjects"]:
                w.writerow([block["grade_num"], block["grade_name"], block["subject_name"],
                            len(block["nodes"]),
                            sum(len(x["children"]) for x in block["nodes"])])
        print(f"  ✔ 覆盖: {cov}")


# ---------------------------------------------------------------- 入库（可选）
def _reference_counts(db) -> Dict[str, int]:
    """统计业务表对知识点的引用行数（sqlite 专用；其他方言跳过检查）。"""
    from sqlalchemy import text  # noqa: E402

    try:
        tables = db.execute(text(
            "SELECT m.name FROM sqlite_master m "
            "JOIN pragma_table_info(m.name) p "
            "WHERE p.name='knowledge_point_id' AND m.type='table'"
        )).all()
    except Exception:  # noqa: BLE001 非 sqlite 方言：放弃检查，交给 --force 兜底
        return {}
    out: Dict[str, int] = {}
    for (tname,) in tables:
        try:
            n = db.execute(text(
                f"SELECT COUNT(*) FROM {tname} WHERE knowledge_point_id IS NOT NULL"
            )).scalar() or 0
        except Exception:  # noqa: BLE001
            continue
        if n:
            out[tname] = int(n)
    return out


def apply_to_db(data: Dict, db_url: str = "", *,
                replace: bool = False, force: bool = False) -> int:
    """幂等入库：按 (父级, 名称) 复用，不覆盖已有内容（与 audit 工具同语义）。

    `replace=True` 时先删除目标 (年级, 学科) 下的既有知识点再导入 —— 即
    「以本套体系替换」，可用于反复重生成。删除会触发外键级联：题目/教案/
    任务挂靠为 SET NULL（保留业务数据、仅解绑考点），掌握/错题类为 CASCADE
    （**会被一并删除**）。因此 replace 前会统计引用行数，存在引用且未传
    force 时拒绝执行。
    """
    backend = os.path.join(ROOT, "backend")
    if backend not in sys.path:
        sys.path.insert(0, backend)
    os.environ.setdefault("LLM_ENABLED", "false")
    from sqlalchemy import create_engine, delete, select  # noqa: E402
    from sqlalchemy.orm import Session  # noqa: E402

    from app.core.config import settings  # noqa: E402
    from app.models import Grade, KnowledgePoint, Subject  # noqa: E402

    url = db_url or os.environ.get("DATABASE_URL") or (
        f"sqlite:///{settings.DATABASE_URL.split('sqlite:///')[-1]}"
        if settings.DATABASE_URL.startswith("sqlite") else "")
    if not url:
        print("✗ 未提供数据库地址（--db 或 DATABASE_URL）")
        return 2
    engine = create_engine(url, future=True, connect_args={"check_same_thread": False})

    stats = {"created": 0, "reused": 0, "deleted": 0}
    missing = []
    with Session(engine) as db:
        grades = {g.grade_num: g for g in db.scalars(select(Grade)).all()}
        subjects = {(s.grade_id, s.name): s for s in db.scalars(select(Subject)).all()}

        targets = []
        for block in data["subjects"]:
            grade = grades.get(int(block["grade_num"]))
            subject = subjects.get((grade.id, block["subject_name"])) if grade else None
            if not grade or not subject:
                missing.append(f"{block['grade_name']}/{block['subject_name']}")
                continue
            targets.append((grade, subject))

        if replace and targets:
            refs = _reference_counts(db)
            if refs and not force:
                print(f"✗ 拒绝替换：以下业务表引用了知识点 {refs}，replace 会级联清理。"
                      f"确认无误请加 --force。")
                return 2
            for grade, subject in targets:
                stats["deleted"] += db.execute(
                    delete(KnowledgePoint).where(
                        KnowledgePoint.grade_id == grade.id,
                        KnowledgePoint.subject_id == subject.id,
                    )
                ).rowcount or 0
            db.flush()
            print(f"  ✔ 已清理目标学科既有知识点 {stats['deleted']} 条")

        def walk(grade, subject, nodes, parent):
            for node in nodes or []:
                name = str(node.get("name") or "").strip()
                if not name:
                    continue
                existing = db.scalar(
                    select(KnowledgePoint).where(
                        KnowledgePoint.grade_id == grade.id,
                        KnowledgePoint.subject_id == subject.id,
                        KnowledgePoint.parent_id == (parent.id if parent else None),
                        KnowledgePoint.name == name,
                    ).limit(1)
                )
                if existing is not None:
                    stats["reused"] += 1
                    cur = existing
                else:
                    cur = KnowledgePoint(
                        name=name, grade_id=grade.id, subject_id=subject.id,
                        parent_id=parent.id if parent else None,
                        level=int(node.get("level") or 1),
                        term=int(node.get("term") or 1),
                        difficulty=str(node.get("difficulty") or "medium"),
                        code=node.get("code"), keywords=node.get("keywords"),
                        description=node.get("description"),
                        source=str(node.get("source") or "seed")[:16],
                        status="published", is_active=True,
                        sort=int(node.get("sort") or 0),
                    )
                    db.add(cur)
                    db.flush()
                    cur.path = (f"{parent.path or parent.id}/{cur.id}"
                                if parent else str(cur.id))
                    stats["created"] += 1
                walk(grade, subject, node.get("children"), cur)

        try:
            for block in data["subjects"]:
                grade = grades.get(int(block["grade_num"]))
                subject = subjects.get((grade.id, block["subject_name"])) if grade else None
                if not grade or not subject:
                    continue
                walk(grade, subject, block["nodes"], None)
            db.commit()
        except Exception as exc:  # noqa: BLE001
            db.rollback()
            print(f"✗ 入库失败（已回滚）: {exc}")
            return 2
    print(f"  ✔ 入库完成：新增 {stats['created']}，复用 {stats['reused']}"
          f"{'，清理 ' + str(stats['deleted']) if replace else ''}"
          f"{'，缺失学科 ' + str(len(missing)) if missing else ''}")
    if missing:
        print(f"    缺失（库中无对应 grade/subject）: {', '.join(missing[:8])}"
              f"{' …' if len(missing) > 8 else ''}")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description="批量生成知识点体系（人教版）")
    ap.add_argument("--grades", default="all", help="年级范围：all / 1-6 / 1,3,5")
    ap.add_argument("--subjects", default="all", help="学科范围：all / 语文,数学")
    ap.add_argument("--format", default="both", choices=["json", "csv", "both"])
    ap.add_argument("--out-dir", default=DEFAULT_OUT,
                    help=f"输出目录（默认 {os.path.relpath(DEFAULT_OUT, ROOT)}）")
    ap.add_argument("--list", action="store_true", help="只打印覆盖矩阵，不写文件")
    ap.add_argument("--apply", action="store_true", help="生成后幂等写入数据库")
    ap.add_argument("--replace", action="store_true",
                    help="配合 --apply：先删除目标 (年级,学科) 既有知识点再导入（以本体系替换）")
    ap.add_argument("--force", action="store_true",
                    help="目标知识点被业务数据引用时，仍允许 --replace（级联清理，慎用）")
    ap.add_argument("--db", default="", help="入库目标库（默认 DATABASE_URL）")
    args = ap.parse_args()

    all_grades = sorted(CURRICULUM)
    all_subjects = []
    for g in all_grades:
        for s in CURRICULUM[g]:
            if s not in all_subjects:
                all_subjects.append(s)
    grades = parse_numbers(args.grades, all_grades, "年级")
    subjects = parse_subjects(args.subjects, all_subjects)

    data = build_tree(grades, subjects)
    if data["meta"]["counts"]["subject_blocks"] == 0:
        print("✗ 选定范围内没有任何课程数据，请检查 --grades/--subjects")
        return 1

    print_matrix(data)
    if args.list:
        return 0

    write_outputs(data, args.out_dir, args.format)
    if args.apply:
        rc = apply_to_db(data, args.db, replace=args.replace, force=args.force)
        if rc:
            return rc
    return 0


if __name__ == "__main__":
    sys.exit(main())
