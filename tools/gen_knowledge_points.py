# ---------------------------------------------------------------- 范围解析
def parse_numbers(spec: str, universe: List[int], label: str) -> List[int]:
    """解析 'all' / '1-6' / '1,3,5' 形式的范围参数。"""
    spec = (spec or "all").strip()
    if spec.lower() == "all":
        return list(universe)
    picked: set = set()
    for part in spec.replace("，", ",").split(","):
        part = part.strip()
        if not part:
            continue
        if "-" in part:
            a, b = part.split("-", 1)
            try:
                lo, hi = int(a), int(b)
            except ValueError:
                raise SystemExit(f"✗ 非法范围: {part}")
            picked.update(range(min(lo, hi), max(lo, hi) + 1))
        else:
            try:
                picked.add(int(part))
            except ValueError:
                raise SystemExit(f"✗ 非法{label}序号: {part}")
    bad = sorted(n for n in picked if n not in universe)
    if bad:
        raise SystemExit(f"✗ {label}超出范围: {bad}（可选 {universe[0]}-{universe[-1]}）")
    return sorted(picked)


def parse_subjects(spec: str, universe: List[str]) -> List[str]:
    spec = (spec or "all").strip()
    if spec.lower() == "all":
        return list(universe)
    picked = []
    for part in spec.replace("，", ",").split(","):
        name = SUBJECT_ALIASES.get(part.strip(), part.strip())
        if not name:
            continue
        if name not in universe:
            raise SystemExit(f"✗ 未知学科: {name}（可选: {', '.join(universe)}）")
        if name not in picked:
            picked.append(name)
    return picked


